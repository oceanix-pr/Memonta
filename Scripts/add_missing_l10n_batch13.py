def main():
    with open(CATALOG, encoding='utf-8') as f:
        catalog = json.load(f)
    strings = catalog['strings']
    for key, vals in T.items():
        entry = strings.setdefault(key, {})
        entry['localizations'] = {
            'zh-Hans': {'stringUnit': {'state': 'translated', 'value': key}},
        }
        for lang, val in zip(LANGS, vals):
            entry['localizations'][lang] = {'stringUnit': {'state': 'translated', 'value': val}}
        entry.pop('extractionState', None)
    text = json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=False,
                      separators=(',', ' : '))
    # 与 Xcode 写盘格式保持一致：空对象渲染为多行空块（"key" : {\n\n    }），
    # 否则重跑本脚本会因 `{}` 与 Xcode 的写法不同而产生整份 diff
    text = re.sub(r'(^([ \t]*)"(?:[^"\\]|\\.)*"\s*: )\{\}(?=,?$)', r'\1{\n\n\2}', text, flags=re.M)
    with open(CATALOG, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'批次13 完成：写入 {len(T)} 个 key（含 zh-Hans 源语言）')


if __name__ == '__main__':
    main()
